#!/usr/bin/env python3
"""Regenerates js/goal-books.js (page kind + grammar + topic per book page) from tools/goal-book-source.json.
Source format: {bookId:{lvl,fam,pages:{n:[kind,[grammarPoints],[topics]]}}}  kind: c card, b bridge/tiny story, p action pairs, s story, w worksheet, o cover/how-to.
Add a new book: add its entry to the source JSON (or hand-add to js/goal-tags.js items) and run:  python3 tools/gen_goal_books.py"""
import json,os
H=os.path.dirname(os.path.abspath(__file__));S=json.load(open(os.path.join(H,'goal-book-source.json')))
out={}
for b,v in sorted(S.items()):
    n=max(int(k) for k in v['pages']);k=['o']*n;g={};t={}
    for p,(kind,gr,tp) in v['pages'].items():
        i=int(p)-1;k[i]=kind
        if kind!='o':
            if gr:g[p]=','.join(gr)
            if tp:t[p]=','.join(tp)
    out[b]={'lvl':v['lvl'],'fam':v['fam'],'k':''.join(k),'g':g,'t':t}
js='/* GENERATED by tools/gen_goal_books.py - do not edit by hand. Page kind, grammar points and topics per book page (page n = PDF page n). */\nwindow.LWGoalBooks='+json.dumps(out,separators=(',',':'))+';\n'
open(os.path.join(H,'..','js','goal-books.js'),'w').write(js);print('wrote',len(js),'bytes',len(out),'books')
